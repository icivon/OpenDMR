#ifndef DM32_CONFIG_SNAPSHOT_H
#define DM32_CONFIG_SNAPSHOT_H

// The menus' OK / Cancel: a copy of everything the settings menus change (the settings, the transmit tones, our extra
// options, the language, the theme, the PINs on or off, the menus' places kept), taken before the first change in a
// list and put back on Cancel or at the power off before OK (list.c, through ui_list_settings_*)
void config_snapshot_init(void); // sets the list hooks, registers the power off restore
void config_snapshot_take(void);
void config_snapshot_restore(void); // put back, saved, applied (backlight, theme, language, GPS)
void config_snapshot_drop(void);    // OK: the changes stay

#endif
